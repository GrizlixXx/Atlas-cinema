export const CATEGORY_I18N: Record<string, string> = {
  Drama: 'Драма',
  Crime: 'Кримінал',
  Action: 'Бойовик',
  Fantasy: 'Фентезі',
  'Sci-Fi': 'Наукова фантастика',
  Thriller: 'Трилер',
  Animation: 'Анімація',
  Romance: 'Романтика',
  Comedy: 'Комедія',
  Adventure: 'Пригоди',
};

export function getLang(): Lang {
  const saved = localStorage.getItem(LS_KEYS.LANG);
  if (saved === 'uk' || saved === 'en') return saved;
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('uk') ? 'uk' : 'en';
}

export function setLang(lang: Lang): void {
  localStorage.setItem(LS_KEYS.LANG, lang);
  window.location.reload();
}

export function t(key: string): string {
  const lang = getLang();
  return I18N[lang]?.[key] ?? I18N.en?.[key] ?? key;
}

export function translateCategory(cat: string): string {
  if (getLang() !== 'uk') return cat;
  return CATEGORY_I18N[cat] || cat;
}

export function applyI18n(root: Document | Element = document): void {
  const lang = getLang();
  if (root instanceof Document) {
    root.documentElement.lang = lang;
  }
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  });
}
